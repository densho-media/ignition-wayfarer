# ---- Blender side (blender -b --python this -- --mode ...) -------------------------------------------------------------------------
def b_model(root):
    """An original synthetic bracket in the probe asset's ART_ collection: a base plate, an upright and a gusset, one PBR material."""
    import bmesh
    import bpy
    from mathutils import Matrix
    name = 'WF_DETAIL_PROBE_AUTH'
    bpy.ops.wm.open_mainfile(filepath=str(root/'assets/wayfarer/detail'/f'{name}.blend'))
    bm = bmesh.new()
    for size, at in (((.30, .20, .02), (0, 0, -.09)), ((.02, .20, .18), (-.14, 0, 0)), ((.12, .02, .10), (-.07, 0, -.03))):
        bmesh.ops.create_cube(bm, size=1.0, matrix=Matrix.Translation(at)@Matrix.Diagonal((*size, 1)))
    me = bpy.data.meshes.new('ProbeBracket_Mesh'); bm.to_mesh(me); bm.free()
    m = bpy.data.materials.new('ProbeSteel'); m.use_nodes = True
    n = next(q for q in m.node_tree.nodes if q.type == 'BSDF_PRINCIPLED')
    n.inputs['Base Color'].default_value = (.55, .32, .12, 1); n.inputs['Roughness'].default_value = .45; n.inputs['Metallic'].default_value = .8
    me.materials.append(m)
    o = bpy.data.objects.new('ProbeBracket', me); o.location = CENTRE
    bpy.data.collections[f'ART_{name}'].objects.link(o)
    bpy.ops.wm.save_mainfile(filepath=bpy.data.filepath)
    print('WF_PROBE', json.dumps(dict(made='ProbeBracket', vertices=len(me.vertices))), flush=True)


def b_art(root, asset, obj):
    """A hand-authored ART_ mesh in a detail asset (local content a rebuild must keep)."""
    import bmesh
    import bpy
    bpy.ops.wm.open_mainfile(filepath=str(root/'assets/wayfarer/detail'/f'{asset}.blend'))
    bm = bmesh.new(); bmesh.ops.create_cube(bm, size=.05); me = bpy.data.meshes.new(obj+'_Mesh'); bm.to_mesh(me); bm.free()
    o = bpy.data.objects.new(obj, me); bpy.data.collections[f'ART_{asset}'].objects.link(o)
    bpy.ops.wm.save_mainfile(filepath=bpy.data.filepath)
    print('WF_PROBE', json.dumps(dict(art=obj, asset=asset)), flush=True)


def b_edit_glb(root):
    """A changed source asset: the committed .glb re-exported with the bracket scaled by 1.1."""
    import bpy
    path = root/'data/detail'/PACK/'probe_bracket.glb'
    bpy.ops.wm.read_factory_settings(use_empty=True); bpy.ops.import_scene.gltf(filepath=str(path))
    for o in bpy.context.scene.objects:
        o.scale = [1.1*x for x in o.scale]; o.select_set(True)
    bpy.ops.export_scene.gltf(filepath=str(path), export_format='GLB', use_selection=True, export_apply=True)
    print('WF_PROBE', json.dumps(dict(edited=str(path))), flush=True)


def b_vehicle(root):
    """The authored mesh as the vehicle evaluates it: at Rotor_1 with an identity local frame, its world vertices equal to the .glb's through
    the anchor, and still on Rotor_1 after the ring turns. Also reports what the saved detail asset holds."""
    import bpy
    sys.path[:0] = [str(root/'src/wayfarer'), str(root/'src/wayfarer/build')]
    from spec import load
    import rotor_interface
    s = load(root)[0]; out = {}
    bpy.ops.wm.read_factory_settings(use_empty=True); bpy.ops.import_scene.gltf(filepath=str(root/'data/detail'/PACK/'probe_bracket.glb'))
    ref = sorted(tuple(round(c, 4) for c in o.matrix_world@v.co) for o in bpy.context.scene.objects if o.type == 'MESH' for v in o.data.vertices)
    bpy.ops.wm.open_mainfile(filepath=str(root/'assets/wayfarer'/(s['vehicle']['asset']+'.blend')))

    def sample():
        bpy.context.scene.frame_set(1); deps = bpy.context.evaluated_depsgraph_get()
        rotor = next(i.matrix_world.copy() for i in deps.object_instances if i.object.original.name == 'Rotor_1')
        inst = [i for i in deps.object_instances if i.object.original.name == OBJ]
        if len(inst) != 1:
            return dict(count=len(inst))
        i = inst[0]; me = i.object.to_mesh(); world = [i.matrix_world@v.co for v in me.vertices]
        local = sorted(tuple(round(c, 4) for c in rotor.inverted()@w) for w in world); i.object.to_mesh_clear()
        frame_err = max(abs(a-b) for ra, rb in zip(i.matrix_world, rotor) for a, b in zip(ra, rb))
        return dict(count=1, frame_err=frame_err, vertex_err=max((max(abs(a-b) for a, b in zip(p, q)) for p, q in zip(local, ref)), default=1.0)
                    if len(local) == len(ref) else 'count differs', rotor_x=rotor.to_euler().x, materials=[m.name for m in i.object.data.materials])
    out['saved'] = sample()
    c = bpy.data.objects[rotor_interface.control(1)]; c['spin_integrated'], c['spin_turned'] = 1.0, 37.0; c.update_tag()
    bpy.data.objects['Rotor_1'].update_tag()
    out['turned'] = sample()
    out['turned']['ring_moved'] = abs(out['turned']['rotor_x']-out['saved']['rotor_x']) > 1e-3 if out['turned'].get('count') == 1 else False
    print('WF_PROBE', json.dumps(out), flush=True)


def b_asset(root, asset):
    """Objects of a saved detail asset: generated, adopted ART and imported authored (names)."""
    import bpy
    bpy.ops.wm.open_mainfile(filepath=str(root/'assets/wayfarer/detail'/f'{asset}.blend'))
    obs = [o for o in bpy.data.objects if o.library is None and o.type == 'MESH']
    print('WF_PROBE', json.dumps(dict(asset=asset, owned=sorted(o.name for o in obs if o.get('wf_owner')),
                                      adopted=sorted(o.name for o in obs if o.get('wf_adopted')),
                                      sources=sorted(o.name for o in obs if o.get('wf_authored_source')))), flush=True)


# ---- Orchestration (plain python3) --------------------------------------------------------------------------------------------------
class Run:
    def __init__(self, work):
        self.work = work; self.steps = []; self.t0 = time.monotonic()

    def sh(self, args, cwd, timeout=3600):
        r = subprocess.run([str(a) for a in args], cwd=cwd, capture_output=True, text=True, timeout=timeout)
        return r.returncode, r.stdout+r.stderr

    def blender(self, clone, mode, *extra):
        code, out = self.sh([BLENDER, '-b', '--factory-startup', '--python-exit-code', '1', '--python', clone/'tests/verify_authored_portable.py',
                             '--', '--mode', mode, '--root', clone, *extra], clone)
        probe = [json.loads(l.split(' ', 1)[1]) for l in out.splitlines() if l.startswith('WF_PROBE ')]
        return code, probe[-1] if probe else None, out

    def workflow(self, clone, *args, timeout=3600):
        code, out = self.sh(['python3', clone/'tools/workflow.py', *args], clone, timeout)
        try:
            return code, json.JSONDecoder().raw_decode(out[out.index('{'):])[0], out
        except ValueError:
            return code, None, out

    def step(self, n, what, ok, **evidence):
        self.steps.append(dict(step=n, what=what, result='PASS' if ok else 'FAIL', seconds=round(time.monotonic()-self.t0, 1), **evidence))
        print(f"[{'PASS' if ok else 'FAIL'}] {n} {what}", flush=True)
        return ok


def tail(out, n=8):
    return [l for l in out.splitlines() if any(w in l for w in ('WF_', 'Error', 'error', 'Traceback', 'FAIL'))][-n:]


def build_all(r, clone):
    code, out = r.sh([BLENDER, '-b', '--factory-startup', '--python-exit-code', '1', '--python', clone/'src/wayfarer/build/build.py', '--',
                      '--root', clone], clone)
    return code, out


def main(work, skip_runtime):
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True); r = Run(work); A, B = work/'a', work/'b'
    rev = subprocess.check_output(['git', '-C', ROOT, 'rev-parse', 'HEAD'], text=True).strip()
    # Clone A: the authoring session.
    r.sh(['git', 'clone', '-q', '--no-hardlinks', ROOT, A], work)
    for k, v in (('user.email', 'probe@example.invalid'), ('user.name', 'portability probe')):
        r.sh(['git', 'config', k, v], A)
    (A/'data/detail'/f'{PACK}.toml').write_text(MANIFEST); (A/'src/wayfarer/detail'/f'pack_{PACK}.py').write_text(CODE)
    code, res, out = r.workflow(A, 'module', 'build', PACK)
    r.step(0, 'clone A: the probe pack builds its (empty) detail asset', code == 0, tail=tail(out))
    code, probe, out = r.blender(A, 'model')
    r.step(1, 'a synthetic bracket is modelled in ART_WF_DETAIL_PROBE_AUTH, independently of the generators', code == 0 and probe, probe=probe)
    code, res, out = r.workflow(A, 'module', 'export-authored', ASM, '--id', ID, '--objects', 'ProbeBracket')
    ok = code == 0 and res and res.get('result') == 'PASS'
    r.step(2, 'module export-authored writes the self-contained .glb', ok, export={k: res.get(k) for k in ('file', 'bytes', 'sha256', 'authored_against')} if res else tail(out))
    if not ok:
        return r
    entry = res['manifest_entry'].replace('<fill in: e.g. CC0-1.0, or the owner\'s licence>', 'CC0-1.0').replace('author = "<fill in>"', 'author = "portability probe (synthetic)"')
    entry = entry.replace('<fill in: how and from what it was made>', 'synthetic bracket modelled with bmesh by tests/verify_authored_portable.py; no external content')
    with open(A/'data/detail'/f'{PACK}.toml', 'a') as f:
        f.write('\n'+entry+'\n')
    r.sh(['git', 'add', f'data/detail/{PACK}.toml', f'data/detail/{PACK}/probe_bracket.glb', f'src/wayfarer/detail/pack_{PACK}.py'], A)
    code, out = r.sh(['git', 'commit', '-q', '-m', 'probe: authored bracket as committed data'], A)
    r.step(3, 'the pack manifest references the .glb; the pack is committed in A', code == 0, tail=out.splitlines()[-3:])
    # Clone B: a fresh checkout of A, no assets and no ignored or local files.
    r.sh(['git', 'clone', '-q', '--no-hardlinks', A, B], work)
    clean = not (B/'assets').exists() and (B/'data/detail'/PACK/'probe_bracket.glb').is_file()
    code, out = build_all(r, B)
    r.step(4, 'clone B (no assets/, the .glb only as committed data): a full build imports it', clean and code == 0 and 'WF_DETAIL WF_DETAIL_PROBE_AUTH 0 generated 1 imported' in out,
           clean_checkout=clean, tail=tail(out))
    code, res, out = r.workflow(B, 'module', 'validate', PACK)
    r.step(5, 'module validate passes (checksum, frame, envelope, saved asset)', code == 0 and res and res['result'] == 'PASS',
           saved=(res or {}).get('saved'), pure=(res or {}).get('pure', {}).get('fails'))
    code, probe, out = r.blender(B, 'vehicle')
    ok = code == 0 and probe and probe['saved'].get('count') == 1 and probe['saved']['frame_err'] < 1e-6 and probe['saved']['vertex_err'] < 2e-4
    r.step(6, 'the vehicle links it at Rotor_1 (identity local frame) and its vertices equal the .glb through the anchor', ok, probe=probe)
    ok = probe is not None and probe['turned'].get('count') == 1 and probe['turned']['ring_moved'] and probe['turned']['frame_err'] < 1e-6
    r.step(7, 'it turns with ring A (instance frame = Rotor_1 after a 37-frame turn)', ok)
    if skip_runtime:
        r.step(8, 'runtime-export (skipped by --skip-runtime)', False, skipped=True)
    else:
        for p in (ROOT/'assets/characters').glob('*.blend'):
            (B/'assets/characters').mkdir(parents=True, exist_ok=True); shutil.copy2(p, B/'assets/characters'/p.name)
        code, res, out = r.workflow(B, 'runtime-export', timeout=7200)
        node = None
        man = B/'godot/generated/manifest.json'
        if man.is_file():
            node = next((n for n in json.loads(man.read_text())['nodes'] if n['component_id'] == f'{ASM}.AUTHORED.{ID}'), None)
        r.step(8, 'runtime-export (fresh workspace build) carries the node on the ring frame and passes its checks',
               code == 0 and res and res.get('result') == 'PASS' and node is not None and node.get('frame') == 'WF.ROTOR.1',
               node=node, result=(res or {}).get('result'), failed=(res or {}).get('step'), tail=(res or {}).get('tail'))
    # 9: a changed source asset and a changed attachment contract.
    code, res, out = r.workflow(B, 'module', 'publish', PACK)
    published = code == 0 and res and res['result'] == 'PASS'
    code, probe, out = r.blender(B, 'edit_glb')
    code, res, out = r.workflow(B, 'module', 'build', PACK)
    stale = code != 0 and 'WF_DETAIL_STALE' in json.dumps(res)+out
    sha = __import__('hashlib').sha256((B/'data/detail'/PACK/'probe_bracket.glb').read_bytes()).hexdigest()
    m = B/'data/detail'/f'{PACK}.toml'; text = m.read_text(); old = text.split('sha256 = "')[1].split('"')[0]
    m.write_text(text.replace(old, sha))
    code, res, out = r.workflow(B, 'module', 'build', PACK); rebuilt = code == 0
    code, res, out = r.workflow(B, 'assembly', 'validate')
    stale_record = res is not None and res['packs'].get(PACK, {}).get('result') == 'FAIL' and any('inputs changed' in f for f in res['packs'][PACK]['fails'])
    others = res is not None and all(v['result'] == 'PASS' for k, v in res['packs'].items() if k != PACK)
    reg = B/'data/modules.toml'; rtext = reg.read_text(); reg.write_text(rtext.replace('interface_version = 1', 'interface_version = 2'))
    code, res, out = r.workflow(B, 'module', 'build', PACK)
    review = code != 0 and 'WF_DETAIL_REVIEW' in json.dumps(res)+out
    reg.write_text(rtext)
    r.step(9, 'a changed .glb stops the build until its checksum is recorded, which stales the publication; a changed contract stops it',
           published and stale and rebuilt and stale_record and others and review,
           published=published, stale_refused=stale, rebuilt_after_sha=rebuilt, publication_stale=stale_record, other_packs_unaffected=others,
           contract_change_refused=review)
    # 10: rebuilding keeps hand-authored meshes elsewhere and in the probe's own asset.
    r.blender(B, 'art', '--asset', 'WF_DETAIL_RA2_EQP', '--obj', 'ArtKeepRa2')
    r.blender(B, 'art', '--asset', 'WF_DETAIL_PROBE_AUTH', '--obj', 'ArtKeepProbe')
    c1, _, o1 = r.workflow(B, 'module', 'build', 'ra2_equip'); c2, _, o2 = r.workflow(B, 'module', 'build', PACK); c3, o3 = build_all(r, B)
    _, ra2, _ = r.blender(B, 'asset', '--asset', 'WF_DETAIL_RA2_EQP'); _, prb, _ = r.blender(B, 'asset', '--asset', 'WF_DETAIL_PROBE_AUTH')
    ok = (not (c1 or c2 or c3) and ra2 and prb and 'ArtKeepRa2' in ra2['adopted'] and 'ArtKeepProbe' in prb['adopted'] and OBJ in prb['owned'])
    r.step(10, 'pack and full rebuilds keep ART meshes (another pack and the probe itself) next to the imported mesh', ok, ra2=ra2, probe=prb,
           tails=[tail(o) for o in (o1, o2, o3) if o])
    r.rev = rev
    return r


if __name__ == '__main__':
    argv = sys.argv[sys.argv.index('--')+1:] if '--' in sys.argv else sys.argv[1:]
    p = argparse.ArgumentParser(); p.add_argument('--mode'); p.add_argument('--root', type=Path); p.add_argument('--asset'); p.add_argument('--obj')
    p.add_argument('--work', type=Path, default=ROOT/'runs'/'authored-portable'); p.add_argument('--skip-runtime', action='store_true')
    a = p.parse_args(argv)
    if a.mode:
        {'model': lambda: b_model(a.root), 'art': lambda: b_art(a.root, a.asset, a.obj), 'edit_glb': lambda: b_edit_glb(a.root),
         'vehicle': lambda: b_vehicle(a.root), 'asset': lambda: b_asset(a.root, a.asset)}[a.mode]()
    else:
        r = main(a.work.resolve(), a.skip_runtime)
        report = dict(source_revision=getattr(r, 'rev', None), work=str(r.work), steps=r.steps,
                      result='PASS' if r.steps and all(s['result'] == 'PASS' for s in r.steps) else 'FAIL')
        (r.work/'report.json').write_text(json.dumps(report, indent=1)+'\n')
        print(json.dumps({k: v for k, v in report.items() if k != 'steps'} | {'steps': {s['step']: s['result'] for s in r.steps}}))
        sys.exit(report['result'] != 'PASS')
