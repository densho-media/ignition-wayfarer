"""Portable authored detail end to end, from clean checkouts (docs/MODULES.md). Disposable: everything happens in two clones under --work;
this checkout is only read (its HEAD and, for runtime-export, its generated character assets).

Clone A (the authoring session): a probe detail pack `authored_probe` (assembly PROBE.AUTH) on the moving anchor WF-RING-A.ROTOR.1 is
added and its detail asset built; an original synthetic bracket (bmesh boxes with one PBR material, no external content) is modelled in
its ART_ collection; `module export-authored` writes data/detail/authored_probe/probe_bracket.glb and the manifest entry is recorded;
the pack is committed. Clone B is a fresh clone of A: no assets, no ignored or local files. In B:

 1-4  the bracket exists only as committed data; a full build imports it into the probe's detail asset in the anchor frame;
 5    module validate (pure screens, the checksum, the frame, the envelope, the saved asset) passes;
 6-7  the vehicle links it: its evaluated instance sits at Rotor_1's world frame, matches the .glb's vertices through the anchor, and
      turns with the ring;
 8    runtime-export (its own fresh workspace build) carries the node, with its record and the ring's runtime frame, and passes its checks;
 9    a changed .glb stops the build (WF_DETAIL_STALE) until its checksum is recorded, which then stales the publication; a bumped
      interface version (a changed attachment contract) stops it (WF_DETAIL_REVIEW);
 10   rebuilds keep hand-authored meshes elsewhere (an ART_ mesh in WF_DETAIL_RA2_EQP and one in the probe's own asset).

    python3 tests/verify_authored_portable.py [--work DIR] [--skip-runtime]
Writes <work>/report.json; exits 1 on any failed step. The character and EVA .blend files runtime-export requires are generated by other
loops (characters, eva) and are copied into B; nothing about the authored path comes from this checkout's local files.
"""
