#!/usr/bin/env python3
"""Consolidated Vertex Drive engineering-problem register (phase close 2026-11-25). Reads, never writes, the study results.

  ENG-030..080  the active register of the compact engine, as the Fusion Engineering page shows it
                (lab/studies/fusion-ignition/results/fusion_ignition.json, built by chapters.py from every vertex-* study)
  ENG-001..021  the remote-engine and dust-shield register of vertex-hims (layouts archived as comparison 2026-11-23)
  X-*           concepts that failed or were set aside, with the reason

    python3 lab/studies/vertex-compact-engine/register.py      # writes lab/studies/vertex-compact-engine/PROBLEMS.md
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
FI = ROOT / 'lab/studies/fusion-ignition/results/fusion_ignition.json'
HIMS = HERE / 'vertex-hims/PROBLEMS.md'
RANK = {'CRITICAL': 0, 'HIGH': 1, 'MEDIUM': 2, 'LOW': 3}


def cell(s):
    return str(s if s not in (None, '') else '-').replace('|', '/').replace('\n', ' ')


def rank(p):
    sev = p.get('severity', '')
    return (0 if p['status'] == 'OPEN' else 1, min((v for k, v in RANK.items() if sev.startswith(k)), default=4), p['id'])


def main():
    d = json.loads(FI.read_text()); P = d['problems']; items = P['items']
    hims = [r for r in HIMS.read_text().splitlines() if re.match(r'\| ENG-0\d\d \|', r)]
    st = {}
    for p in items:
        st[p['status']] = st.get(p['status'], 0) + 1
    out = ['# Vertex Drive: consolidated engineering-problem register', '',
           'Generated by `register.py` from the study results (phase close 2026-11-25). Research, not canon: every figure below is a model '
           'result or a PROTOTYPE choice, never a validated specification. Nothing here closes the engine; all OPEN items stay open for the '
           'next Vertex phase.', '',
           f"Active register ENG-030..080: {len(items)} problems ({', '.join(f'{v} {k}' for k, v in sorted(st.items()))}). "
           f"Archived register ENG-001..021 (remote layouts and dust shielding): {len(hims)} problems. Set-aside concepts: {len(P['concepts'])}.", '',
           '## Active register (compact engine, research geometry)', '',
           'Ordered: open before closed, then by severity. Evidence paths are relative to the repository root; `work/` paths name where a '
           'study ran before it moved to `lab/studies/vertex-compact-engine/`.', '',
           '| ID | Problem | Subsystem | Severity | Status | Required | Achieved | Next step | Maturity |',
           '| --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for p in sorted(items, key=rank):
        out.append('| ' + ' | '.join(cell(p.get(k)) for k in ('id', 'title', 'subsystem', 'severity', 'status', 'required', 'achieved', 'next', 'maturity')) + ' |')
    out += ['', '## Archived register (remote engines and dust shielding, vertex-hims)', '',
            'The remote and distributed layouts are kept as a non-canonical comparison (owner 2026-11-23); detail in `vertex-hims/PROBLEMS.md`.', '',
            '| ID | Problem | Subsystem | Required | Achieved | Severity | Status |', '| --- | --- | --- | --- | --- | --- | --- |', *hims,
            '', '## Concepts that failed or were set aside', '', '| ID | Concept | Why |', '| --- | --- | --- |']
    for c in P['concepts']:
        out.append(f"| {cell(c.get('id'))} | {cell(c.get('title') or c.get('label'))} | {cell(c.get('why') or c.get('reason') or c.get('verdict'))} |")
    out += ['', '## Evidence by problem', '']
    for p in sorted(items, key=lambda q: q['id']):
        out.append(f"- **{p['id']}** {cell(p.get('title'))}: {cell(p.get('mechanism'))} Assumptions: {cell(p.get('assumptions'))}. "
                   f"Needed advance: {cell(p.get('advances'))}. Evidence: `{cell(p.get('evidence'))}`.")
    (HERE / 'PROBLEMS.md').write_text('\n'.join(out) + '\n')
    print(len(items), 'active', st, len(hims), 'archived', len(P['concepts']), 'concepts')


if __name__ == '__main__':
    main()
