"""Data tables and the Pareto figure from results/ron.json (standard library only).

  python3 lab/studies/vertex-compact-engine/vertex-ron/tables.py      writes results/tables.md, results/variants.csv and figures/pareto.svg
"""
import csv
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
D = json.loads((HERE/'results'/'ron.json').read_text())
V, K = D['variants'], D['canon']
FAM = {'compact': ('A compact', '#8a8f98'), 'intermediate': ('B intermediate', '#2a7de1'), 'remote': ('C remote F', '#d6611a'),
       'distributed': ('D distributed', '#1f9e6e'), 'hybrid': ('E hybrid', '#b03fbf')}


def fam(r):
    f = r['family']
    return 'remote' if r['name'].startswith('C_') else f


def f(x, n=0):
    return '∞' if not math.isfinite(x) else f'{x:,.{n}f}'


def main():
    rows = []
    for n, r in V.items():
        L, m, s, p, c = r['ledger'], r['mass_t'], r['ship'], r['particles'], r['capture']
        rows.append(dict(variant=n, family=FAM[fam(r)][0], D_m=r['params']['D_m'], S_m=r['params']['S_m'],
                         rings=';'.join(f'x{x:.0f}/R{rr:.0f}' for x, rr, _ in r['params']['rings']), current_x=r['mult'],
                         field_ratio=c['field_ratio'], hit=p['hit_energy_share'], forward=p['forward_energy_share'],
                         forward_cone_deg=p['forward_cone_p95_deg'] or 0.0, eta=p['axial_efficiency'], cant_deg=r['cant_deg'],
                         ship_offset_deg=r.get('ship_offset_deg', 0.0),
                         piped_GW_x4=4*L['B01_W']/1e9, self_GW_x4=4*L['self_W']/1e9, cold_GW_x4=4*L['cold_W']/1e9,
                         plug_T_K=next((q['T_K'] for q in L['rows'] if q['part'] == 'PLUG'), None),
                         nose_T_K=max([q['T_K'] for q in L['rows'] if q['part'].startswith('RING') and q.get('T_K')] or [0]),
                         engine_t=r['engine_t'], **{k: v for k, v in m.items()},
                         dry_t=s['dry_t'], departure_t=s['departure_t'], propellant_t=s['propellant_t'], ve_km_s=s['ve_eff_m_s']/1e3,
                         thrust_MN=s['thrust_N']/1e6, accel_g=s['accel_g_departure'], burn1_days=s['burn1_days']))
    keys = sorted({k for r in rows for k in r}, key=lambda k: list(rows[1].keys()).index(k) if k in rows[1] else 99)
    with open(HERE/'results'/'variants.csv', 'w', newline='') as fh:
        w = csv.DictWriter(fh, fieldnames=keys); w.writeheader(); w.writerows(rows)
    md = ['# RON data tables (generated by tables.py from results/ron.json)', '',
          f"Canon reference: departure {K['departure_kg']/1e3:,.0f} t, dry {K['dry_kg']/1e3:,.0f} t, drive package {K['drive_package_kg']/1e3:.0f} t, "
          f"drive hot-radiator share {K['drive_W']/1e9:.2f} GW, 4 burns of {K['dv_burn']/1e3:,.0f} km/s, ve {K['ve_eff']/1e3:,.0f} km/s.", '',
          '## Architecture summary (four engines)', '',
          '| Variant | D m | Current x capture | Field/pulse | Eta | Cant deg | Piped GW | Self-radiated GW | Engine t | Departure t | Burn 1 d |',
          '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for r in rows:
        md.append(f"| {r['variant']} | {r['D_m']:.0f} | {r['current_x']} | {f(r['field_ratio'],1)} | {r['eta']:.2f} | {r['cant_deg']:.1f} | "
                  f"{f(r['piped_GW_x4'],1)} | {f(r['self_GW_x4'],0)} | {f(r['engine_t'])} | {f(r['departure_t'])} | {f(r['burn1_days'],1)} |")
    md += ['', '## Mass by part (t per engine)', '', '| Variant | Conductor | Coil structure | Cryostat | Nose | Fins | Plug | Boom | Blades | Cage+shield |',
           '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for r in rows:
        md.append(f"| {r['variant']} | " + ' | '.join(f(r.get(k, 0.0)) for k in ('conductor_t', 'coil_structure_t', 'cryostat_t', 'nose_t', 'fins_t', 'plug_t',
                                                                              'boom_t', 'blades_t', 'cage_and_shield_t')) + ' |')
    md += ['', '## Sensitivities (quick statistics, n 24/40; ±0.6 kt noise against the n 160 runs)', '',
           '| Variant | Case | Engine t | Departure t | Eta | Cant deg |', '| --- | --- | --- | --- | --- | --- |']
    for n, cases in D.get('sensitivity', {}).items():
        for c in cases:
            md.append(f"| {n} | {c['case']} | {c['engine_t']:,.0f} | {c['departure_t']:,.0f} | {c['eta']:.3f} | {c['cant']:.1f} |")
    (HERE/'results'/'tables.md').write_text('\n'.join(md)+'\n')
    pareto(rows)


def pareto(rows):
    """Departure mass against the deployed engine-to-ship distance (a proxy for deployment, dynamics and dust exposure)."""
    pts = [r for r in rows if math.isfinite(r['departure_t'])]
    W, H, ml, mr, mt, mb = 760, 460, 70, 170, 30, 50
    x0, x1, y0, y1 = 0, 2200, 0, 32000
    X = lambda v: ml+(v-x0)/(x1-x0)*(W-ml-mr); Y = lambda v: H-mb-(v-y0)/(y1-y0)*(H-mt-mb)
    front, best = [], math.inf
    for r in sorted(pts, key=lambda r: r['D_m']):
        if r['departure_t'] < best:
            best = r['departure_t']; front.append(r)
    s = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="system-ui, sans-serif" font-size="12">',
         f'<rect width="{W}" height="{H}" fill="#ffffff"/>',
         f'<text x="{ml}" y="18" font-size="14" fill="#1b1e23">Departure mass vs engine-to-ship distance (four engines, V2, today\'s tape)</text>']
    for v in range(0, 32001, 8000):
        s.append(f'<line x1="{ml}" x2="{W-mr}" y1="{Y(v):.1f}" y2="{Y(v):.1f}" stroke="#e3e5e8"/>'
                 f'<text x="{ml-8}" y="{Y(v)+4:.1f}" text-anchor="end" fill="#5b616b">{v/1000:.0f} kt</text>')
    for v in range(0, 2201, 500):
        s.append(f'<text x="{X(v):.1f}" y="{H-mb+18}" text-anchor="middle" fill="#5b616b">{v} m</text>')
    s.append(f'<line x1="{ml}" x2="{W-mr}" y1="{Y(K["departure_kg"]/1e3):.1f}" y2="{Y(K["departure_kg"]/1e3):.1f}" stroke="#1b1e23" stroke-dasharray="4 3"/>'
             f'<text x="{W-mr+6}" y="{Y(K["departure_kg"]/1e3)+4:.1f}" fill="#1b1e23">canon 4,426 t</text>')
    s.append('<polyline fill="none" stroke="#1b1e23" stroke-width="2" points="' + ' '.join(f'{X(r["D_m"]):.1f},{Y(r["departure_t"]):.1f}' for r in front) + '"/>')
    for r in pts:
        col = FAM[next(k for k, v in FAM.items() if v[0] == r['family'])][1]
        s.append(f'<circle cx="{X(r["D_m"]):.1f}" cy="{Y(r["departure_t"]):.1f}" r="5" fill="{col}" stroke="#ffffff" stroke-width="2">'
                 f'<title>{r["variant"]}: {r["departure_t"]:,.0f} t, engine {r["engine_t"]:,.0f} t, eta {r["eta"]:.2f}</title></circle>')
    for r in front:
        s.append(f'<text x="{X(r["D_m"])+8:.1f}" y="{Y(r["departure_t"])-8:.1f}" fill="#1b1e23">{r["variant"]}</text>')
    for i, (lab, col) in enumerate(v for k, v in FAM.items() if k != 'compact'):
        s.append(f'<circle cx="{W-mr+14}" cy="{mt+40+i*20}" r="5" fill="{col}"/><text x="{W-mr+24}" y="{mt+44+i*20}" fill="#1b1e23">{lab}</text>')
    s.append(f'<text x="{W-mr+6}" y="{mt+150}" fill="#5b616b">A compact: fails</text><text x="{W-mr+6}" y="{mt+164}" fill="#5b616b">(heat, not plotted)</text>')
    s.append(f'<text x="{(ml+W-mr)/2}" y="{H-12}" text-anchor="middle" fill="#5b616b">burn-to-ship distance D (deployment, dynamics and dust exposure grow to the right)</text>')
    s.append('</svg>')
    (HERE/'figures').mkdir(exist_ok=True); (HERE/'figures'/'pareto.svg').write_text('\n'.join(s))


main()
