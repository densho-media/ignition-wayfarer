"""Writes TABLES.md from environment.json, exposure.json and impacts.json (no new physics).
    python3 lab/variants/vertex-drive/studies/dust/tables.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ENV = json.load(open(os.path.join(HERE, "environment.json")))
EXP = json.load(open(os.path.join(HERE, "exposure.json")))
IMP = json.load(open(os.path.join(HERE, "impacts.json")))
E_T = ENV["meta"]["energy_thresholds_J"]


def g(x, n=3):
    if x is None:
        return "none"
    if x == 0:
        return "0"
    return f"{x:.{n}g}"


def main():
    L = ["# T02 tables (generated by `tables.py`; do not edit by hand)", "",
         "Research, not canon. Frame metres, +X bow. Bow-first = grains travel -X (acceleration and coast); engine-first = grains travel +X "
         "(braking). Areas are stream-projected (frontal). Cones: 0 aligned, 0.4 deg dust aberration envelope at 4,797 km/s, 2.29 deg "
         "P11 diagnostic, 5 deg P11 prototype.", ""]
    r = EXP["p11_reproduction"]
    L += ["## 1. P11 reproduction (bow-first, V0, canon 90 m shield, aligned)", "",
          f"Engine maximum radius {r['engine_max_radius_m']} m, {r['critical_exposed']} critical parts exposed, "
          f"{r['exposed_frontal_area_m2']} m2 frontal: matches P11 = **{r['matches_P11']}**.", ""]
    L += ["## 2. Exposure map: critical frontal area outside every silhouette (m2, parts)", "",
          "| Ship | Orientation | Protection | 0 deg | 0.4 deg | 2.29 deg | 5 deg | Forward-shield parts seen (m2, 0.4 deg) |",
          "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for ship, o in EXP["cases"].items():
        for orient, opts in o.items():
            for on, c in opts.items():
                cells = [f"{c[k]['exposed_frontal_area_m2']:,.0f} ({c[k]['critical_exposed']})" for k in ("0", "0.4", "2.29061", "5")]
                fs = c["0.4"].get("forward_shield_parts_exposed_frontal_m2", 0.0) if orient == "ENGINE_FIRST" else "n/a (it is the shield)"
                L.append(f"| {ship} | {orient} | {on} | " + " | ".join(cells) + f" | {fs if isinstance(fs, str) else f'{fs:,.0f}'} |")
    L += ["", "### 2a. By system at 0.4 deg (m2, parts)", "", "| Ship | Orientation | Protection | System | Parts | Exposed m2 |", "| --- | --- | --- | --- | --- | --- |"]
    for ship in ("V1", "CANON"):
        for orient, opts in EXP["cases"][ship].items():
            for on, c in opts.items():
                for sysn, v in c["0.4"]["by_system"].items():
                    L.append(f"| {ship} | {orient} | {on} | {sysn} | {v['parts']} | {v['exposed_frontal_area_m2']:,.1f} |")
    L += ["", "V0 and V2 rows are in `exposure.json` (V0 adds the r 12-14 m driver galleries in engine-first; V2 equals V1 apart from the wings).",
          "", "### 2b. Radiators (planar, edge-on to an on-axis stream): exposed planform, frontal at the cone, exposed leading edge", "",
          "| Ship | Orientation | Protection | Cone | Planform m2 | Exposed planform m2 | Frontal m2 | Exposed leading edge m |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for ship, o in EXP["radiators"].items():
        for orient, opts in o.items():
            for on, cones in opts.items():
                for cone, rows in cones.items():
                    L.append(f"| {ship} | {orient} | {on} | {cone} | {sum(x['planform_m2'] for x in rows):,.0f} | {sum(x['exposed_planform_m2'] for x in rows):,.0f} | "
                             f"{sum(x['frontal_worst_in_cone_m2'] for x in rows):,.0f} | {sum(x['leading_edge_exposed_m'] for x in rows):,.0f} |")
    L += ["", "Leading-edge frontal area = exposed edge length x edge thickness (UNKNOWN; 1 cm of edge adds ~1 % of the length in m2).", ""]
    L += ["## 3. Mission legs and fluence per m2 (environment cases)", "",
          "| Ship | Leg | Orientation | Path AU | Days | Case | Energy fluence J/m2 | N(>1 kJ)/m2 | N(>10 kJ)/m2 | N(>1 MJ)/m2 | N(>100 MJ)/m2 | Gas H /cm2 |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for ship, legs in ENV["ships"].items():
        for leg in legs:
            for case, c in leg["cases"].items():
                col = [sum(c["column_N_gt_E_per_m2"][p][k] for p in c["column_N_gt_E_per_m2"]) for k in range(len(E_T))]
                gH = (c["gas_column_per_m2"]["p"] + c["gas_column_per_m2"]["H0"]) * 1e-4
                days = leg.get("days")
                L.append(f"| {ship} | {leg['id']} {leg['name']} | {leg['orientation']} | {c['path_AU']:,.1f} | {g(days)} | {case} | "
                         f"{g(sum(c['energy_fluence_J_m2'].values()))} | {g(col[E_T.index(1e3)])} | {g(col[E_T.index(1e4)])} | {g(col[E_T.index(1e6)])} | {g(col[E_T.index(1e8)])} | {g(gH)} |")
    L += ["", "## 4. Expected impacts above each failure energy over the whole mission", "",
          "Failure energies (NOMINAL crater coefficient): " + ", ".join(f"{k} {g(v)} J" for k, v in IMP["failure_energies_J"]["NOMINAL"].items()) +
          ". 'bare_5mm_wall' = perforation of an unprotected 5 mm metal wall; 'bumper_S<x>' = beyond what a bumper at stand-off x defeats.", "",
          "| Configuration | Case | Bare 5 mm wall | Bumper 1 m | Bumper 2 m | Bumper 10 m | 100 m stand-off | Stand-off for < 0.1 events (all / engine-first / bow-first), m |",
          "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for name, h in IMP["hits"].items():
        for case, c in h["cases"].items():
            t = c["total"]
            L.append(f"| {name} | {case} | {g(t['bare_5mm_wall']['expected_failures'])} | {g(t['bumper_S1m']['expected_failures'])} | {g(t['bumper_S2m']['expected_failures'])} | "
                     f"{g(t['bumper_S10m']['expected_failures'])} | {g(t['skirt_or_shield_S100m']['expected_failures'])} | "
                     f"{g(c['standoff_for_0p1_failures_m'])} / {g(c['standoff_engine_first_only_m'])} / {g(c['standoff_bow_first_only_m'])} |")
    L += ["", "Per leg (NOMINAL), expected events beyond a 2 m bumper:", "", "| Configuration | " + " | ".join(f"leg {i+1}" for i in range(6)) + " |", "| --- |" + " --- |" * 6]
    for name, h in IMP["hits"].items():
        legs = h["cases"]["NOMINAL"]["legs"]
        cells = [f"{l['leg']} {l['orientation'][0]}: {g(l['bumper_S2m'])}" for l in legs] + [""] * (6 - len(legs))
        L.append(f"| {name} | " + " | ".join(cells) + " |")
    L += ["", "## 5. Canon Brow facing, bow-first legs (6,362 m2): events beyond the 2 m disruptor, beyond 10 m, above 1 MJ, above 100 MJ", "",
          "| Path | Case | > 2 m disruptor | > 10 m | > 1 MJ | > 100 MJ |", "| --- | --- | --- | --- | --- | --- |"]
    for ship, cs in IMP["brow_bow_first"].items():
        for case, v in cs.items():
            L.append(f"| {ship} | {case} | {g(v['beyond_disruptor_2m'])} | {g(v['beyond_10m'])} | {g(v['beyond_1MJ'])} | {g(v['beyond_100MJ'])} |")
    L += ["", "## 6. Bumper stand-off and the grain it defeats (cloud fluence model)", "", "| Stand-off m | E defeated (nominal / band) J | Grain at cruise kg | Diameter mm |", "| --- | --- | --- | --- |"]
    for b in IMP["bumper_defeat_vs_standoff"]:
        L.append(f"| {b['S_m']:g} | {g(b['E_nominal_J'])} ({g(b['E_low_J'])}-{g(b['E_high_J'])}) | {g(b['grain_mass_at_cruise_kg'])} | {b['grain_d_mm']:.3f} |")
    L += ["", "## 7. Uniform erosion per leg (NOMINAL environment), crater coefficient LOW / NOMINAL / HIGH, and gas", "",
          "| Ship | Leg | Orientation | Dust energy fluence J/m2 | Erosion um | H fluence /cm2 | Sputter nm (Y 1e-3 / 1e-2) |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for ship, cs in IMP["erosion"].items():
        for e in cs["NOMINAL"]:
            er = e["dust_erosion_um"]
            sp = e["gas_sputter_erosion_nm"]
            L.append(f"| {ship} | {e['leg']} | {e['orientation']} | {g(e['dust_energy_fluence_J_m2'])} | {g(er['LOW'], 2)} / {g(er['NOMINAL'], 2)} / {g(er['HIGH'], 2)} | "
                     f"{g(e['gas_H_column_per_cm2'], 2)} | {g(sp['Y=1e-3'], 2)} / {g(sp['Y=1e-2'], 2)} |")
    s = IMP["skirt"]
    L += ["", "## 8. Skirt geometry (T02-NEW-1)", "", "| Generation | Half-angle deg | r from-to m | x from-to m | Slant m | Surface m2 | Projected m2 | Mass t at 0.5 / 1 / 2 kg/m2 |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for gen, k in s.items():
        m = k["areal_density_options"]
        L.append(f"| {gen} | {k['half_angle_deg']:.2f} | {k['r_from_m']:.1f}-{k['r_to_m']:.0f} | {k['x_from_m']:.1f} to {k['x_to_m']:.1f} | {k['slant_m']:.0f} | {k['surface_m2']:,.0f} | "
                 f"{k['projected_m2']:,.0f} | {m['0.5_kg_m2']['mass_t']:.0f} / {m['1_kg_m2']['mass_t']:.0f} / {m['2_kg_m2']['mass_t']:.0f} |")
    c = IMP["canon_skirt"]
    L.append(f"| CANON (flat) | 90 | {c['r_from_m']}-{c['r_to_m']:.0f} | {c['x_m']} | - | {c['projected_m2']:,.0f} | {c['projected_m2']:,.0f} | "
             f"{c['mass_t_at_kg_m2']['1.0']:.0f} / {c['mass_t_at_kg_m2']['2.0']:.0f} / {c['mass_t_at_kg_m2']['5.0']:.0f} (1 / 2 / 5 kg/m2) |")
    open(os.path.join(HERE, "TABLES.md"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
