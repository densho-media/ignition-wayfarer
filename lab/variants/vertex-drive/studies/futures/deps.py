"""T06 dependency matrix: breakthrough x breakthrough and breakthrough x engine parameter.

  python3 lab/variants/vertex-drive/studies/futures/deps.py      # writes DEPENDENCY_MATRIX.md and DEPENDENCY_MATRIX.json (seconds)

Reads (never writes) registry/technologies.toml and registry/links.toml, plus this folder's registry_proposal.toml and
results/futures.json (run futures.py first). Cell codes: R = requires (depends_on), E = enables, I = improves, W = worsens,
C = conflicts, S = shares hardware; lower case = proposed by T06 (registry_proposal.toml), not yet in the registry.
"""
import json
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ATLAS = HERE.parents[1]
CODE = {'enables': 'E', 'improves': 'I', 'worsens': 'W', 'conflicts': 'C', 'shares': 'S'}


def load():
    T = tomllib.load(open(ATLAS / 'registry/technologies.toml', 'rb'))['technology']
    L = tomllib.load(open(ATLAS / 'registry/links.toml', 'rb'))['link']
    P = tomllib.load(open(HERE / 'registry_proposal.toml', 'rb'))
    F = json.loads((HERE / 'results/futures.json').read_text())
    return T, L, P, F


def main():
    T, L, P, F = load()
    recs = list(T) + P.get('technology', [])
    ids = [t['id'] for t in recs]
    name = {t['id']: t['name'] for t in recs}
    cred = {t['id']: t['credibility'] for t in recs}
    M = {a: {b: '' for b in ids} for a in ids}
    # workstream-level links are attached to every technology of that workstream only when no technology-level link exists
    ws = {}
    for t in recs:
        ws.setdefault(t['workstream'], []).append(t['id'])

    def targets(x):
        return [x] if x in M else []

    def add(a, b, code):
        for x in targets(a):
            for y in targets(b):
                if x != y and code not in M[x][y]:
                    M[x][y] += code
    for t in recs:
        for d in t.get('depends_on', []):
            add(t['id'], d, 'R')
    for l in L:
        add(l['from'], l['to'], CODE[l['kind']])
    for l in P.get('link', []):
        add(l['from'], l['to'], CODE[l['kind']].lower())
    # engine-parameter sensitivities (elasticities at V1c) by technology
    E = F['elasticities']
    par = []
    for r in E['rows']:
        par.append({'lever': r['lever'], 'path': r['path'], 'value': r['value'], 'tech': r['tech'], 'elasticity': r['elasticity']})
    out = {'cells': {a: {b: v for b, v in row.items() if v} for a, row in M.items()}, 'names': name, 'credibility': cred,
           'engine_parameters': par, 'base': E['base'], 'base_departure_t': E['departure_t'],
           'legend': 'R requires, E enables, I improves, W worsens, C conflicts, S shares; lower case = T06 proposal'}
    (HERE / 'DEPENDENCY_MATRIX.json').write_text(json.dumps(out, indent=1) + '\n')
    short = {i: i.replace('VTX-', '').replace('T06-NEW-', 'N') for i in ids}
    md = ['# T06 dependency matrix (generated)', '',
          '_Generated by `deps.py` from the Atlas registry (read-only), `registry_proposal.toml` and `results/futures.json`; do not edit by hand._',
          '', '## Breakthrough x breakthrough', '',
          'Row acts on column. ' + out['legend'] + '. Workstream records (VTX-01 ... VTX-08) are rows and columns of their own; a link the '
          'registry states for a workstream is not copied to its technologies.', '',
          '| | ' + ' | '.join(short[i] for i in ids) + ' |', '|---|' + '---|' * len(ids)]
    for a in ids:
        md.append(f'| **{short[a]}** | ' + ' | '.join(M[a][b] or '·' for b in ids) + ' |')
    md += ['', '| Key | Record | Credibility |', '|---|---|---|'] + [f'| {short[i]} | {i} {name[i]} | {cred[i]} |' for i in ids]
    md += ['', f'## Breakthrough x engine parameter (elasticity of departure mass at {E["base"]}, {E["departure_t"]:,.0f} t)', '',
           'd ln(departure) / d ln(parameter), from +-10 % FDP-1 solves. Negative: raising the parameter lightens the ship.', '',
           '| Technology | Parameter | Value | Elasticity |', '|---|---|---|---|']
    for p in sorted(par, key=lambda p: -abs(p['elasticity'] or 0)):
        md.append(f'| {p["tech"]} | `{p["path"]}` | {p["value"]:g} | {p["elasticity"]:+.2f} |')
    md += ['', '## Records outside the T06 elasticity table', '',
           'No T06 lever represents these. Some have an Atlas case (VTX-06A galleries_r4p5, VTX-04B V1_keep_idle_H2, VTX-03A through the '
           'nozzle-efficiency band); the rest (dust, control, diagnostics, deflection, curtains, isotopes, Fiji) change the integrated engine '
           'only through mechanisms the FDP-1 calculator does not represent, so their effect is UNKNOWN until a thread models it.', '']
    with_par = set()
    for p in par:
        for tok in p['tech'].split('/'):
            with_par.add(tok if tok.startswith(('VTX-', 'T06-')) else 'VTX-' + tok)
    md.append(', '.join(i for i in ids if i not in with_par) + '.')
    md.append('')
    (HERE / 'DEPENDENCY_MATRIX.md').write_text('\n'.join(md))
    print(f'{len(ids)} records, {sum(len(v) for v in out["cells"].values())} non-empty cells')


if __name__ == '__main__':
    main()
